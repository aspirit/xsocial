// mustNewLimiter creates a Limiter from config (memory or cache). Exits on error when storage=cache but cache is nil.
func mustNewLimiter(baseDeps *dep.BaseDeps) ratelimit.Limiter {
	switch baseDeps.Config.RateLimit.Storage {
	case ratelimit.StorageCache:
		if baseDeps.Cache == nil {
			fmt.Fprintf(os.Stderr, "ratelimit: storage is cache but cache is not configured (set storage.redis.address)\n")
			os.Exit(1)
		}
		lim, err := ratelimit.NewCacheLimiter(baseDeps.Cache, baseDeps.Logger)
		if err != nil {
			fmt.Fprintf(os.Stderr, "ratelimit cache: %v\n", err)
			os.Exit(1)
		}

		return lim
	default:
		return ratelimit.NewMemoryLimiter()
	}
}

// applyTrustedProxies configures which reverse proxies Gin trusts for client-IP
// resolution. An empty/nil list trusts no proxy, so ClientIP() returns the
// direct connection address and X-Forwarded-For cannot be spoofed.
func applyTrustedProxies(engine *gin.Engine, proxies []string) error {
	if err := engine.SetTrustedProxies(proxies); err != nil {
		return fmt.Errorf("set trusted proxies: %w", err)
	}

	return nil
}

// ResolveRateLimitPolicies fills method, pattern, match_type, key_mode from the router policy table,
// and default window when not set in config. Call before ValidateRateLimitConfig.
func ResolveRateLimitPolicies(rl *config.RateLimitConfig) error {
	for i := range rl.Policies {
		p := &rl.Policies[i]
		def, ok := router.GetRateLimitPolicyDef(p.Name)
		if !ok {
			return fmt.Errorf("ratelimit.policies[%d].name %q unknown: %w", i, p.Name, internalerr.ErrRateLimitPolicyUnknown)
		}
		p.Method = def.Method
		p.Pattern = def.Pattern
		p.MatchType = def.MatchType
		p.KeyMode = def.KeyMode
		if p.Window == "" {
			p.Window = def.DefaultWindow
		}
	}

	return nil
}

func validateStartupConfig(cfg *config.Config) {
	// Fail-fast on a weak JWT signing key in production: the Ed25519 key is
	// derived from this secret, so low entropy means forgeable tokens. In
	// non-release mode we only warn so local dev with a short key still runs.
	if err := config.ValidateJWTConfig(cfg); err != nil {
		if cfg.Project.Mode == config.ModeRelease {
			fmt.Fprintf(os.Stderr, "FATAL: %v\n", err)
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "WARNING: %v (allowed in %s mode; set a strong JWT_KEY before release)\n", err, cfg.Project.Mode)
	}

	// Production must not run without rate limiting (auth endpoints would be
	// unprotected); fail fast rather than silently exposing them.
	if err := config.ValidateRateLimitEnabled(cfg); err != nil {
		fmt.Fprintf(os.Stderr, "FATAL: %v\n", err)
		os.Exit(1)
	}
}

//	@title			xsocial API
//	@version		0.1.0
//	@BasePath		/v1
//	@schemes		https http
//	@description	Architecture showcase API: posts, likes and asynchronous notifications over MongoDB, Redis and Kafka. Send a stable <b>X-Device-ID</b> header so rate limits key on device rather than shared IPs.
//
//	@securityDefinitions.apikey	BearerAuth
//	@in							header
//	@name						Authorization
//	@description				JWT Bearer token. Format: Bearer {access_token}

func main() {
	// Load configuration once
	cfg := config.GetConfig()
	validateStartupConfig(cfg)

	// Initialize base dependencies
	baseDeps, err := dep.NewBaseDeps(config.ServiceAPI, cfg)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error initializing base dependencies: %v\n", err)
		os.Exit(1)
	}

	// Ensure MongoDB indexes before starting (idempotent).
	coreDB, err := baseDeps.GetDatabase(mongostorage.DBCore)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error getting core database: %v\n", err)
		os.Exit(1)
	}
	if err := indexes.EnsureIndexes(context.Background(), coreDB); err != nil {
		fmt.Fprintf(os.Stderr, "Error ensuring indexes: %v\n", err)
		os.Exit(1)
	}

	// Build the whole object graph with Wire (single entry point, no partial graph)
	allDeps, err := wire.InitializeAPIDeps(baseDeps)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error initializing API dependencies: %v\n", err)
		os.Exit(1)
	}

	// Initialize OpenTelemetry provider
	otelCfg := config.GetOtelConfig()
	otelCfg.Logger = baseDeps.Logger
	otelProvider, err := otelutil.NewOtelProvider(context.Background(), otelCfg)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error initializing OTel provider: %v\n", err)
		os.Exit(1)
	}
	otelutil.DefaultTelemetry = otelProvider

	// Initialize HTTP server
	gin.SetMode(baseDeps.Config.Project.Mode)
	engine := gin.Default()

	// Restrict which proxies may set X-Forwarded-For so ClientIP() (used for
	// rate-limit keys and geo policy) cannot be spoofed. Empty list = trust none.
	if err := applyTrustedProxies(engine, baseDeps.Config.Services.API.TrustedProxies); err != nil {
		fmt.Fprintf(os.Stderr, "Error setting trusted proxies: %v\n", err)
		os.Exit(1)
	}

	// Setup routes
	// Security headers first so every response (incl. preflight/errors) is covered.
	engine.Use(middleware.SecurityHeaders(middleware.SecurityHeadersConfig{
		EnableHSTS: baseDeps.Config.Project.Mode == config.ModeRelease,
	}))
	engine.Use(middleware.CORS(baseDeps.Config.Services.API.CORS))
	engine.Use(otelutil.Middleware(baseDeps.Config.Services.API.ID))
	engine.Use(middleware.RequestContextDetector())
	engine.Use(middleware.Logging(baseDeps.Logger))
	engine.GET("/status", func(c *gin.Context) {
		c.JSON(http.StatusOK, gin.H{
			"ip":   c.ClientIP(),
			"time": time.Now().UnixMilli(),
		})
	})

	// Build/version info for ops (stamped via -ldflags at build time).
	engine.GET("/version", func(c *gin.Context) {
		c.JSON(http.StatusOK, version.Get())
	})

	// Add Swagger documentation route (only in debug mode)
	if baseDeps.Config.Project.Mode == config.ModeDebug {
		engine.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))
	}

	v1 := engine.Group(router.RouteVersionV1)

	// Rate limit: mount on v1 so /status and /swagger are not limited
	if baseDeps.Config.RateLimit.Enabled {
		if err := ResolveRateLimitPolicies(&baseDeps.Config.RateLimit); err != nil {
			fmt.Fprintf(os.Stderr, "ratelimit resolve policies: %v\n", err)
			os.Exit(1)
		}
		if err := config.ValidateRateLimitConfig(baseDeps.Config); err != nil {
			fmt.Fprintf(os.Stderr, "ratelimit config invalid: %v\n", err)
			os.Exit(1)
		}
		lim := mustNewLimiter(baseDeps)
		v1.Use(middleware.RateLimiter(lim, &baseDeps.Config.RateLimit, baseDeps.Logger))
	}

	// Register routes
	router.Register(v1, allDeps)

	// Create server configuration directly from baseDeps
	serverConfig := &baseDeps.Config.Services.API

	// Start server with graceful shutdown
	if err := server.StartWithDeps(engine, serverConfig, baseDeps); err != nil {
		fmt.Fprintf(os.Stderr, "Error starting server: %v\n", err)
		shutdownCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		otelProvider.Shutdown(shutdownCtx)
		cancel()
		os.Exit(1)
	}

	// Normal shutdown: flush the event producer and remaining spans before exit.
	if err := allDeps.Publisher.Close(); err != nil {
		fmt.Fprintf(os.Stderr, "Error closing event publisher: %v\n", err)
	}
	shutdownCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	otelProvider.Shutdown(shutdownCtx)
	cancel()
}
